export const SocialEmpathyHelpingView: React.FC<SocialEmpathyHelpingViewProps> = ({
  currentGrade,
  soundVolume,
  onEarnStar,
}) => {
  const [levelIndex, setLevelIndex] = useState(0);

  const gradeLevels = useMemo(() => {
    const list = HELPING_SCENARIOS.filter((s) => s.grade === currentGrade);
    return list.length > 0 ? list : HELPING_SCENARIOS;
  }, [currentGrade]);

  const activeScenario = gradeLevels[levelIndex] || gradeLevels[0];

  // กระจายคำตอบที่ถูกต้องไปยังตำแหน่งตัวเลือกต่างๆ อย่างเท่าเทียมกัน (หมุนเวียนตำแหน่ง 0, 1, 2 ตามลำดับด่าน)
  const distributedOptions = useMemo(() => {
    const opts = [...activeScenario.options];
    const rot = (activeScenario.levelNumber - 1) % opts.length;
    if (rot === 1) {
      return [opts[2], opts[0], opts[1]]; // helpful is at index 1
    } else if (rot === 2) {
      return [opts[1], opts[2], opts[0]]; // helpful is at index 2
    }
    return opts; // helpful is at index 0
  }, [activeScenario]);

  const [selectedOptionId, setSelectedOptionId] = useState<string | null>(null);
  const [isAnswered, setIsAnswered] = useState(false);
  const [isHelpful, setIsHelpful] = useState(false);

  useEffect(() => {
    setSelectedOptionId(null);
    setIsAnswered(false);
    setIsHelpful(false);

    if (soundVolume > 0) {
      speakText(`${activeScenario.situation} ${activeScenario.voicePrompt}`, 'th', soundVolume);
    }
  }, [activeScenario, soundVolume]);

  const handleSelectOption = (option: {
    id: string;
    text: string;
    emoji: string;
    isHelpful: boolean;
    feedback: string;
  }) => {
    if (isAnswered) return;

    setSelectedOptionId(option.id);
    setIsAnswered(true);
    setIsHelpful(option.isHelpful);

    if (option.isHelpful) {
      soundEffects.playVictory(soundVolume);
      if (onEarnStar) onEarnStar();
      triggerRoundSuccessConfetti({
        starCount: 3,
        isPerfect: true,
        origin: { x: 0.5, y: 0.5 },
      });
      speakText(option.feedback, 'th', soundVolume);
    } else {
      soundEffects.playIncorrect(soundVolume);
      speakText(option.feedback, 'th', soundVolume);
    }
  };

  const handleReset = () => {
    soundEffects.playTap(soundVolume);
    setSelectedOptionId(null);
    setIsAnswered(false);
    setIsHelpful(false);
  };

  const handleNextLevel = () => {
    soundEffects.playTap(soundVolume);
    if (levelIndex < gradeLevels.length - 1) {
      setLevelIndex((prev) => prev + 1);
    } else {
      setLevelIndex(0);
    }
  };

  return (
    <div className="w-full max-w-4xl mx-auto flex flex-col items-center gap-4">
      {/* Level Selector */}
      <SkillGameLevelSelector
        levels={gradeLevels.map((l) => ({ level: l.levelNumber, name: l.title }))}
        currentLevel={levelIndex + 1}
        onSelectLevel={(num) => setLevelIndex(num - 1)}
        accentColor="pink"
        prefix="ด่าน"
      />

      {/* Main Scenario Container */}
      <div className="w-full bg-white rounded-3xl p-4 sm:p-6 border-2 border-pink-200 shadow-sm flex flex-col items-center gap-4">
        {/* Header */}
        <div className="w-full flex items-center justify-between pb-3 border-b border-pink-100 flex-wrap gap-2">
          <div className="flex items-center gap-2.5">
            <div className="w-12 h-12 rounded-2xl bg-pink-100 border border-pink-300 flex items-center justify-center text-2xl shadow-2xs">
              🤝
            </div>
            <div>
              <h2 className="text-base sm:text-lg font-black text-pink-950">
                {activeScenario.title}
              </h2>
              <div className="text-xs text-pink-700 font-bold">
                สถานการณ์จำลอง: น้ำใจและการช่วยเหลือผู้อื่น
              </div>
            </div>
          </div>

          <button
            type="button"
            onClick={() => speakText(`${activeScenario.situation} ${activeScenario.voicePrompt}`, 'th', soundVolume)}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-pink-50 hover:bg-pink-100 text-pink-800 text-xs font-bold border border-pink-200 cursor-pointer"
            title="ฟังเสียงบรรยายสถานการณ์"
          >
            <Volume2 className="w-4 h-4" />
            <span>ฟังเสียงโจทย์</span>
          </button>
        </div>

        {/* Situation Spotlight Banner */}
        <div className="w-full bg-gradient-to-r from-pink-50 via-rose-50 to-amber-50 rounded-3xl p-4 sm:p-5 border-2 border-pink-200 flex flex-col sm:flex-row items-center gap-4 text-center sm:text-left">
          <div className="w-20 h-20 rounded-3xl bg-white border-2 border-pink-300 flex items-center justify-center text-5xl shadow-xs shrink-0 animate-bounce hover:animate-none">
            {activeScenario.sceneEmoji}
          </div>
          <div>
            <div className="text-xs font-black text-pink-900 bg-white/80 inline-block px-2.5 py-0.5 rounded-full border border-pink-200 mb-1">
              📍 เหตุการณ์ที่เกิดขึ้น
            </div>
            <p className="text-sm sm:text-base font-black text-slate-800 leading-snug">
              {activeScenario.situation}
            </p>
            <p className="text-xs sm:text-sm font-bold text-pink-900 mt-1">
              ❓ {activeScenario.question}
            </p>
          </div>
        </div>

        {/* Choices Options Grid */}
        <div className="w-full flex flex-col gap-2.5">
          <div className="text-xs font-bold text-slate-500 px-1">
            แตะเลือกคำตอบที่แสดงถึงน้ำใจที่ดีงาม:
          </div>

          {distributedOptions.map((opt) => {
            const isSelected = selectedOptionId === opt.id;
            let cardStyle =
              'bg-slate-50 hover:bg-pink-50/50 border-slate-200 hover:border-pink-300';

            if (isSelected) {
              cardStyle = opt.isHelpful
                ? 'bg-emerald-50 border-emerald-400 ring-4 ring-emerald-100 shadow-md'
                : 'bg-rose-50 border-rose-300 ring-4 ring-rose-100';
            }

            return (
              <button
                key={opt.id}
                type="button"
                onClick={() => handleSelectOption(opt)}
                disabled={isAnswered}
                className={`w-full p-3.5 sm:p-4 rounded-2xl border-2 transition-all cursor-pointer flex items-center justify-between gap-3 text-left ${cardStyle}`}
              >
                <div className="flex items-center gap-3 min-w-0">
                  <span className="text-3xl shrink-0">{opt.emoji}</span>
                  <span className="text-xs sm:text-sm font-black text-slate-800 leading-tight">
                    {opt.text}
                  </span>
                </div>

                {isSelected && (
                  <div className="shrink-0">
                    {opt.isHelpful ? (
                      <CheckCircle2 className="w-6 h-6 text-emerald-600" />
                    ) : (
                      <XCircle className="w-6 h-6 text-rose-500" />
                    )}
                  </div>
                )}
              </button>
            );
          })}
        </div>

        {/* Feedback & Actions */}
        {isAnswered && (
          <div
            className={`w-full p-4 rounded-2xl border-2 flex flex-col sm:flex-row items-center justify-between gap-3 animate-in zoom-in-95 duration-200 text-center sm:text-left ${
              isHelpful
                ? 'bg-emerald-50 border-emerald-300 text-emerald-950'
                : 'bg-rose-50 border-rose-300 text-rose-950'
            }`}
          >
            <div className="flex items-center gap-2.5">
              <span className="text-2xl">{isHelpful ? '🎉' : '💡'}</span>
              <div>
                <div className="font-black text-sm sm:text-base">
                  {isHelpful ? 'ยอดเยี่ยมมาก! ได้รับ 1 ดาวสะสม ⭐' : 'ยังไม่ถูกต้องนะจ๊ะ'}
                </div>
                <div className="text-xs font-medium mt-0.5">
                  {activeScenario.options.find((o) => o.id === selectedOptionId)?.feedback}
                </div>
              </div>
            </div>

            <div className="flex items-center gap-2 shrink-0">
              {!isHelpful && (
                <button
                  type="button"
                  onClick={handleReset}
                  className="flex items-center gap-1.5 px-4 py-2 rounded-xl bg-white text-rose-700 font-black text-xs border border-rose-300 cursor-pointer shadow-xs"
                >
                  <RotateCcw className="w-3.5 h-3.5" />
                  <span>ลองใหม่</span>
                </button>
              )}

              {isHelpful && (
                <button
                  type="button"
                  onClick={handleNextLevel}
                  className="flex items-center gap-1.5 px-5 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-700 text-white font-black text-xs shadow-md cursor-pointer active:scale-95"
                >
                  <span>ด่านต่อไป</span>
                  <ArrowRight className="w-4 h-4" />
                </button>
              )}
            </div>
          </div>
        )}

        {/* Empathy Moral Note */}
        <div className="w-full bg-pink-50/80 border border-pink-200 rounded-2xl p-3 flex items-start gap-2 text-xs text-pink-950 font-medium">
          <Heart className="w-4 h-4 text-pink-600 shrink-0 mt-0.5 fill-pink-200" />
          <span>
            <strong>ข้อคิดน้ำใจ:</strong> {activeScenario.empathyMoral}
          </span>
        </div>
      </div>
    </div>
  );
};
