/**
 * Fetch an AI-generated story from backend with automatic fallback to curated bank
 */
export async function fetchOrGeneratePreGameStory(
  skillId: Subject,
  grade: Grade = 'K2',
  childName: string = 'น้องคนเก่ง',
  curriculumMode: string = 'early_childhood'
): Promise<PreGameStory> {
  const fallbackStory = CURATED_STORIES[skillId] || CURATED_STORIES.math;

  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 8000); // 8-second timeout for fast preschool UX

    const response = await fetch('/api/story/generate', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        skillId,
        grade,
        childName,
        curriculumMode,
      }),
      signal: controller.signal,
    });

    clearTimeout(timeoutId);

    if (response.ok) {
      const data = await response.json();
      if (data.success && data.story && data.story.title && data.story.paragraphs) {
        return {
          id: `ai-${Date.now()}`,
          skillId,
          skillTag: data.story.skillTag || fallbackStory.skillTag,
          grade,
          title: data.story.title,
          heroEmoji: fallbackStory.heroEmoji,
          moral: data.story.moral || fallbackStory.moral,
          paragraphs: data.story.paragraphs,
          isAiGenerated: true,
        };
      }
    }
  } catch (err) {
    console.info('Using curated offline story for preschool agility:', err);
  }

  // Graceful fallback to rich curated story
  return {
    ...fallbackStory,
    grade,
    title: fallbackStory.title.replace('น้องคนเก่ง', childName),
    isAiGenerated: false,
  };
}
