export function getActivitiesBySkill(skillId: string): EarlyChildhoodActivity[] {
  return EARLY_CHILDHOOD_ACTIVITIES.filter(
    (act) => act.skillId === skillId || (skillId === 'thai' && act.skillId === 'literacy')
  );
}

export function getActivityById(id: string): EarlyChildhoodActivity | undefined {
  return EARLY_CHILDHOOD_ACTIVITIES.find((act) => act.id === id);
}
